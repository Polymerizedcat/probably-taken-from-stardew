#!/usr/bin/env python3
"""Builds Mods/StardewPortal/Bridge/payload.json.

The game's mod scanner hard-blocks any .dll/.exe/.bat inside a mod folder and
flags high-entropy blobs, so every payload file is stored as gzip + base64
inside one plain-text JSON file. StardewPortal.dll unpacks it at runtime.
"""
import base64
import gzip
import json
import os

ROOT = r"D:\EntertainmentsPro\SteamLibrary\steamapps\common\Probably Stolen"
SV_SRC = os.path.join(ROOT, ".dsh_tools", "src", "sv")
SMAPI = os.path.join(ROOT, ".dsh_tools", "smapi_payload")
OUT = os.path.join(ROOT, "Mods", "StardewPortal", "Bridge", "payload.json")

# overridable for a checkout that is not inside the game folder
ROOT = os.environ.get("PS_ROOT", ROOT)
SV_SRC = os.environ.get("SV_SRC", SV_SRC)
SMAPI = os.environ.get("SMAPI_PAYLOAD", SMAPI)
OUT = os.environ.get("PAYLOAD_OUT", OUT)


def pack(data):
    return base64.b64encode(gzip.compress(data, 9)).decode("ascii")


def entry(root, relpath, data):
    return {"root": root, "path": relpath.replace("\\", "/"), "gzip": True, "b64": pack(data)}


def main():
    files = []

    # ---- the Stardew-side mod module
    module = [
        ("manifest.json", os.path.join(SV_SRC, "manifest.json")),
        ("DeepSpacePortal.dll", os.path.join(SV_SRC, "bin", "DeepSpacePortal.dll")),
        ("assets/portal.png", os.path.join(SV_SRC, "assets", "portal.png")),
    ]
    for rel, path in module:
        with open(path, "rb") as handle:
            files.append(entry("mod", rel, handle.read()))

    # ---- bundled SMAPI (only written when the player has no SMAPI yet)
    for base, _dirs, names in os.walk(SMAPI):
        for name in sorted(names):
            if name.lower() == "steam_appid.txt":
                continue
            full = os.path.join(base, name)
            rel = os.path.relpath(full, SMAPI)
            with open(full, "rb") as handle:
                files.append(entry("root", rel, handle.read()))

    payload = {
        "version": 1,
        "priceMultiplier": 2.0,
        "note": "Generated by .dsh_tools/src/sv/pack_payload.py - do not edit by hand.",
        "files": files,
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, ensure_ascii=False, separators=(",", ":"))

    size = os.path.getsize(OUT)
    print(f"wrote {OUT} ({size/1024/1024:.2f} MB, {len(files)} files)")


if __name__ == "__main__":
    main()
